import assert from 'node:assert/strict';
import {days,documentStatus,vehicleStatus,blankVehicle,csvCell} from '../lib/fleet.ts';
const now='2026-09-21';
assert.equal(days('2026-09-21',now),0);
assert.equal(documentStatus('',now),'Missing');
assert.equal(documentStatus('2026-09-20',now),'Expired');
assert.equal(documentStatus('2026-09-21',now),'Due soon');
assert.equal(documentStatus('2026-10-21',now),'Due soon');
assert.equal(documentStatus('2026-10-22',now),'Valid');
assert.equal(days('2028-03-01','2028-02-28'),2);
assert.equal(vehicleStatus({...blankVehicle,roadworthy:'2026-09-20'},now),'Expired');
assert.equal(vehicleStatus({...blankVehicle,roadworthy:'2026-12-01'},now),'Missing');
assert.equal(vehicleStatus({...blankVehicle,roadworthy:'2026-12-01',insurance:'2026-10-21'},now),'Due soon');
assert.equal(vehicleStatus({...blankVehicle,roadworthy:'2026-12-01',insurance:'2026-12-21'},now),'Valid');
assert.equal(csvCell('=HYPERLINK("evil")'),'"\'=HYPERLINK(""evil"")"');
assert.equal(csvCell('a,"b"'),'"a,""b"""');
console.log('13 expiry, precedence, leap-year and CSV safety checks passed.');
